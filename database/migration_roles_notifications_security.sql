USE janets_catering;

-- Existing accounts stay usable; verification applies to accounts created from now on
UPDATE `users` SET `is_verified` = 1;

-- SMS verification removed
DROP TABLE IF EXISTS `sms_verifications`;
ALTER TABLE `users` DROP COLUMN IF EXISTS `phone_verified`;

-- Only two roles
UPDATE `users` SET `role` = 'ADMIN' WHERE `role` = 'STAFF';
ALTER TABLE `users` MODIFY `role` ENUM('ADMIN','OWNER') NOT NULL DEFAULT 'ADMIN';
ALTER TABLE `users` ADD CONSTRAINT `chk_users_role` CHECK (`role` IN ('ADMIN','OWNER'));

-- One account per phone number (NULL = no number given, allowed many times)
UPDATE `users` SET `contact_number` = NULL WHERE TRIM(`contact_number`) = '';
ALTER TABLE `users` ADD UNIQUE KEY `uq_users_contact` (`contact_number`);

-- Single-use, expiring email links (only the SHA-256 of a token is stored)
DROP TABLE IF EXISTS `email_verifications`;
CREATE TABLE `email_verifications` (
  `id`         INT AUTO_INCREMENT PRIMARY KEY,
  `user_id`    INT NOT NULL,
  `email`      VARCHAR(100) NOT NULL,
  `token_hash` CHAR(64) NOT NULL,
  `expires_at` DATETIME NOT NULL,
  `used_at`    DATETIME NULL,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY `uq_ev_token` (`token_hash`),
  KEY `idx_ev_user` (`user_id`),
  CONSTRAINT `fk_ev_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Notification history: who did it, which log event caused it, no duplicates per user + event
ALTER TABLE `notifications`
  ADD COLUMN IF NOT EXISTS `actor_user_id` INT NULL AFTER `reference_type`,
  ADD COLUMN IF NOT EXISTS `actor_username` VARCHAR(100) NULL AFTER `actor_user_id`,
  ADD COLUMN IF NOT EXISTS `activity_log_id` INT NULL AFTER `actor_username`,
  ADD UNIQUE KEY IF NOT EXISTS `uq_notification_event` (`user_id`, `activity_log_id`),
  ADD KEY IF NOT EXISTS `idx_notification_created` (`user_id`, `created_at`);

-- Backup access is fixed to the ADMIN role
DELETE FROM `system_settings` WHERE `setting_key` = 'backup_admin_can_create';

