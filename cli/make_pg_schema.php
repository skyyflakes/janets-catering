<?php
/**
 * Builds database/postgres/janets_catering_pg.sql (PostgreSQL / Supabase) from the live MySQL database.
 * Run from the command line on the XAMPP computer:  php cli/make_pg_schema.php
 *
 * Every table, column, default, key, index, foreign key and check constraint is converted. Text columns become
 * CITEXT so comparisons stay case-insensitive like MySQL. "ON UPDATE CURRENT_TIMESTAMP" becomes a trigger.
 * The activity-log triggers come from includes/pg_audit.php, the same definitions the system installs itself.
 */
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
require __DIR__ . '/../config/database.php';
require __DIR__ . '/../includes/activity_logger.php';
require_once __DIR__ . '/../includes/pg_audit.php';

$my = getDBConnection();
if (!$my || jq_is_pg()) exit("Run this against the MySQL database (DB_DRIVER must be mysql).\n");
$db = DB_NAME;
$q = static function (string $sql, array $a = []) use ($my) { $s = $my->prepare($sql); $s->execute($a); return $s->fetchAll(PDO::FETCH_ASSOC); };
$id = static fn(string $n) => '"' . str_replace('"', '""', $n) . '"';

function pg_type(array $c): string
{
    $t = strtolower($c['COLUMN_TYPE']);
    return match (true) {
        str_starts_with($t, 'enum('), str_contains($t, 'char'), str_contains($t, 'text') => 'citext',
        str_starts_with($t, 'bigint') => 'bigint',
        str_starts_with($t, 'int'), str_starts_with($t, 'mediumint') => 'integer',
        str_starts_with($t, 'smallint') => str_contains($t, 'unsigned') ? 'integer' : 'smallint',
        str_starts_with($t, 'tinyint') => 'smallint',
        str_starts_with($t, 'decimal') => 'numeric' . substr($t, 7),
        str_starts_with($t, 'double'), str_starts_with($t, 'float') => 'double precision',
        $t === 'date' => 'date',
        $t === 'time' => 'time(0)',
        str_starts_with($t, 'datetime'), str_starts_with($t, 'timestamp') => 'timestamp(' . (int)($c['DATETIME_PRECISION'] ?? 0) . ')',
        str_contains($t, 'blob') => 'bytea',
        default => throw new RuntimeException("Unmapped type {$c['COLUMN_TYPE']} ({$c['TABLE_NAME']}.{$c['COLUMN_NAME']})"),
    };
}

function pg_default(array $c): ?string
{
    $d = $c['COLUMN_DEFAULT'];
    if ($d === null || strtoupper($d) === 'NULL') return null;
    if (preg_match('/^current_timestamp(\(\d?\))?$/i', $d)) return 'CURRENT_TIMESTAMP';
    if (preg_match("/^'(.*)'$/s", $d, $m)) return "'" . str_replace("'", "''", str_replace("\\'", "'", $m[1])) . "'";
    if (is_numeric($d)) return $d;
    throw new RuntimeException("Unmapped default $d ({$c['TABLE_NAME']}.{$c['COLUMN_NAME']})");
}

$tables = array_column($q("SELECT TABLE_NAME FROM information_schema.TABLES WHERE TABLE_SCHEMA = ? AND TABLE_TYPE = 'BASE TABLE' ORDER BY TABLE_NAME", [$db]), 'TABLE_NAME');
$out = ["-- Janet's Quality Catering: complete database structure for PostgreSQL (Supabase), version " . JQ_AUDIT_SCHEMA_VERSION,
        "-- Generated from the MySQL database by cli/make_pg_schema.php. Run it once in an empty database (Supabase: SQL Editor).",
        "-- Then load the data with cli/copy_to_pg.php, or the reference data from the MySQL seed files.", '',
        'CREATE EXTENSION IF NOT EXISTS citext;', '',
        "-- Sets a column to the current time when a row changes (MySQL's ON UPDATE CURRENT_TIMESTAMP).",
        "CREATE OR REPLACE FUNCTION jq_touch() RETURNS trigger LANGUAGE plpgsql AS \$f\$
BEGIN
    IF to_jsonb(NEW) IS DISTINCT FROM to_jsonb(OLD) AND (to_jsonb(NEW) -> TG_ARGV[0]) IS NOT DISTINCT FROM (to_jsonb(OLD) -> TG_ARGV[0]) THEN
        NEW := jsonb_populate_record(NEW, jsonb_build_object(TG_ARGV[0], localtimestamp(0)));
    END IF;
    RETURN NEW;
END \$f\$;", ''];
$after = [];
$touch = [];
foreach ($tables as $t) {
    $cols = $q("SELECT * FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY ORDINAL_POSITION", [$db, $t]);
    $lines = [];
    foreach ($cols as $c) {
        $type = pg_type($c);
        $line = '    ' . $id($c['COLUMN_NAME']) . ' ' . $type;
        if (str_contains($c['EXTRA'], 'auto_increment')) {
            $line .= ' GENERATED BY DEFAULT AS IDENTITY';
        } elseif (($def = pg_default($c)) !== null) {
            $line .= ' DEFAULT ' . $def;
        }
        if ($c['IS_NULLABLE'] === 'NO') $line .= ' NOT NULL';
        if (str_starts_with(strtolower($c['COLUMN_TYPE']), 'enum(')) {
            $line .= ' CHECK (' . $id($c['COLUMN_NAME']) . ' IN ' . substr($c['COLUMN_TYPE'], 4) . ')';
        }
        $lines[] = $line;
        if (stripos($c['EXTRA'], 'on update current_timestamp') !== false) $touch[] = [$t, $c['COLUMN_NAME']];
    }
    $idx = [];
    foreach ($q("SELECT INDEX_NAME, NON_UNIQUE, COLUMN_NAME FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? ORDER BY INDEX_NAME, SEQ_IN_INDEX", [$db, $t]) as $r) {
        $idx[$r['INDEX_NAME']]['unique'] = !(int)$r['NON_UNIQUE'];
        $idx[$r['INDEX_NAME']]['cols'][] = $id($r['COLUMN_NAME']);
    }
    if (isset($idx['PRIMARY'])) $lines[] = '    PRIMARY KEY (' . implode(', ', $idx['PRIMARY']['cols']) . ')';
    foreach ($q("SELECT CONSTRAINT_NAME, CHECK_CLAUSE FROM information_schema.CHECK_CONSTRAINTS WHERE CONSTRAINT_SCHEMA = ? AND TABLE_NAME = ?", [$db, $t]) as $ck) {
        if (preg_match('/^`?\w+`?\s+in\s*\(/i', $ck['CHECK_CLAUSE']) && str_starts_with($ck['CONSTRAINT_NAME'], 'CONSTRAINT_')) continue; // enum checks already added
        $expr = str_replace('`', '"', $ck['CHECK_CLAUSE']);
        $expr = preg_replace('/\s+regexp\s+/i', ' ~ ', $expr);
        $lines[] = '    CONSTRAINT ' . $id($ck['CONSTRAINT_NAME']) . ' CHECK (' . $expr . ')';
    }
    $out[] = "CREATE TABLE " . $id($t) . " (\n" . implode(",\n", $lines) . "\n);";
    foreach ($idx as $name => $ix) {
        if ($name === 'PRIMARY') continue;
        $pgName = substr($t . '__' . $name, 0, 63);
        $out[] = 'CREATE ' . ($ix['unique'] ? 'UNIQUE ' : '') . 'INDEX ' . $id($pgName) . ' ON ' . $id($t) . ' (' . implode(', ', $ix['cols']) . ');';
    }
    $out[] = '';
}
$fks = $q("SELECT k.TABLE_NAME, k.CONSTRAINT_NAME, k.COLUMN_NAME, k.REFERENCED_TABLE_NAME, k.REFERENCED_COLUMN_NAME, r.DELETE_RULE, r.UPDATE_RULE
             FROM information_schema.KEY_COLUMN_USAGE k
             JOIN information_schema.REFERENTIAL_CONSTRAINTS r ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME AND r.TABLE_NAME = k.TABLE_NAME
            WHERE k.TABLE_SCHEMA = ? AND k.REFERENCED_TABLE_NAME IS NOT NULL ORDER BY k.TABLE_NAME, k.CONSTRAINT_NAME, k.ORDINAL_POSITION", [$db]);
$out[] = '-- Foreign keys';
foreach ($fks as $f) {
    $out[] = 'ALTER TABLE ' . $id($f['TABLE_NAME']) . ' ADD CONSTRAINT ' . $id(substr($f['TABLE_NAME'] . '__' . $f['CONSTRAINT_NAME'], 0, 63))
        . ' FOREIGN KEY (' . $id($f['COLUMN_NAME']) . ') REFERENCES ' . $id($f['REFERENCED_TABLE_NAME']) . ' (' . $id($f['REFERENCED_COLUMN_NAME']) . ')'
        . ' ON DELETE ' . $f['DELETE_RULE'] . ' ON UPDATE ' . $f['UPDATE_RULE'] . ';';
}
$out[] = '';
$out[] = "-- Columns that update themselves when a row changes";
foreach ($touch as [$t, $c]) {
    $out[] = 'CREATE TRIGGER ' . $id(substr("trg_touch_{$t}_{$c}", 0, 63)) . ' BEFORE UPDATE ON ' . $id($t) . " FOR EACH ROW EXECUTE FUNCTION jq_touch('$c');";
}
$out[] = '';
$out[] = "-- Supabase also publishes every table through its web API. Row-level security with no policies closes that door;";
$out[] = "-- the system connects as the tables' owner, which row-level security does not restrict.";
foreach ($tables as $t) {
    $out[] = 'ALTER TABLE ' . $id($t) . ' ENABLE ROW LEVEL SECURITY;';
}
$out[] = '';
$out[] = '-- Hosted (Vercel) storage: sign-in sessions and uploaded files. Not used on XAMPP.';
$out[] = jq_pg_hosted_tables_sql();
$out[] = '';
$out[] = '-- Activity log: functions and triggers (the same ones includes/pg_audit.php installs)';
$columns = [];
foreach ($q("SELECT TABLE_NAME, COLUMN_NAME, COLUMN_KEY FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = ? ORDER BY TABLE_NAME, ORDINAL_POSITION", [$db]) as $r) {
    $columns[$r['TABLE_NAME']]['columns'][] = $r['COLUMN_NAME'];
    if ($r['COLUMN_KEY'] === 'PRI' && !isset($columns[$r['TABLE_NAME']]['pk'])) $columns[$r['TABLE_NAME']]['pk'] = $r['COLUMN_NAME'];
}
foreach (jq_pg_trigger_statements($columns) as $sql) $out[] = rtrim($sql, ";\n ") . ';';
$out[] = '';
$out[] = "INSERT INTO system_settings (setting_key, setting_value) VALUES ('audit_schema_version', '" . JQ_AUDIT_SCHEMA_VERSION . "')"
       . " ON CONFLICT (setting_key) DO UPDATE SET setting_value = EXCLUDED.setting_value;";

$dir = __DIR__ . '/../database/postgres';
if (!is_dir($dir)) mkdir($dir, 0755, true);
file_put_contents("$dir/janets_catering_pg.sql", implode("\n", $out) . "\n");
echo 'Wrote database/postgres/janets_catering_pg.sql: ', count($tables), ' tables, ', count($fks), ' foreign keys, ', count($touch), " auto-update columns.\n";
